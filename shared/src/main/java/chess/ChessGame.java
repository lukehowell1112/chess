    /**
     * reads over the entire board to find the king position
     *
     * @param teamColor
     * @param board
     * @return
     */
    private ChessPosition findKing(ChessGame.TeamColor teamColor, ChessBoard board) {
        for (int row = 1; row <= 8; row++) {
            for (int col = 1; col <= 8; col++) {
                ChessPosition position = new ChessPosition(row, col);
                ChessPiece piece = board.getPiece(position);
                if (piece != null && piece.getTeamColor() == teamColor && piece.getPieceType() == ChessPiece.PieceType.KING) {
                    return position;
                }
            }
        }
        return null;
    }

    /**
     * checks each enemy piece to see if its moves will capture the king
     *
     * @param teamColor
     * @param board
     * @return
     */
    private boolean kingInCheck(ChessGame.TeamColor teamColor, ChessBoard board) {
        ChessPosition kingPosition = findKing(teamColor, board);

        for (int row = 1; row <= 8; row++) {
            for (int col = 1; col <= 8; col++) {
                ChessPosition position = new ChessPosition(row, col);
                ChessPiece piece = board.getPiece(position);
                if (piece != null && piece.getTeamColor() != teamColor) {
                    Collection<ChessMove> possibleMoves = piece.pieceMoves(board, position);
                    for (ChessMove move : possibleMoves) {
                        if (move.getEndPosition().equals(kingPosition)) {
                            return true;
                        }
                    }
                }
            }
        }
        return false;
    }

    /**
     * Gets all valid moves for a piece at the given location
     *
     * @param startPosition the piece to get valid moves for
     * @return Set of valid moves for requested piece, or null if no piece at
     * startPosition
     */
    public Collection<ChessMove> validMoves(ChessPosition startPosition) {

        ChessPiece piece = board.getPiece(startPosition);

        if (piece == null) {
            return null;
        }
        Collection<ChessMove> possibleMoves = piece.pieceMoves(board, startPosition);
        Collection<ChessMove> realMoves = new ArrayList<>();

        for (ChessMove move : possibleMoves) {
            ChessBoard boardCopy = new ChessBoard(board); // copy the board
            ChessPiece movingPiece = boardCopy.getPiece(move.getStartPosition()); // get the piece

            if (move.getPromotionPiece() == null) {
                boardCopy.addPiece(move.getEndPosition(), movingPiece); // move the piece to the new position
            } else {
                boardCopy.addPiece(move.getEndPosition(), new ChessPiece(piece.getTeamColor(), move.getPromotionPiece()));
            }

            boardCopy.addPiece(move.getStartPosition(), null); // delete the old piece

            if (!(kingInCheck(piece.getTeamColor(), boardCopy))) {
                realMoves.add(move);
            }
        }
        return realMoves;
    }

